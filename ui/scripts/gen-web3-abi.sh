#!/usr/bin/env bash
# Export the contract ABIs and method selectors from web3/out into src/lib/web3/abi.ts.
# Run after `forge build` in web3/ whenever a contract's public interface changes; the output is
# committed so the UI builds without Foundry.
#   WEB3_DIR   path to the web3 project (default ../web3)
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
web3="${WEB3_DIR:-$here/../web3}"
out="$here/src/lib/web3/abi.ts"
command -v jq >/dev/null || { echo "jq is required" >&2; exit 69; }
emit() {
  local f="$web3/out/$1.sol/$1.json"
  [ -r "$f" ] || { echo "missing $f: run forge build in $web3" >&2; exit 1; }
  printf '/** %s: ABI and 4-byte selectors (hex, no 0x). */\nexport const %s = {\n  abi: %s,\n  methods: %s\n} as const;\n\n' \
    "$1" "$2" "$(jq -c .abi "$f")" "$(jq -c .methodIdentifiers "$f")"
}
mkdir -p "$(dirname "$out")"
{
  printf '// Generated by ui/scripts/gen-web3-abi.sh from web3/out. Do not edit by hand.\n\n'
  emit EtchedAnchor etchedAnchor
  emit HireContract hireContract
} > "$out"
echo "wrote $out"
